@dataclass
class Attachment(object):
    """Represents an attachment associated with a Gmail message.
    Attributes:
        filename (str): Name of the attachment file.
        mimeType (str): MIME type of the attachment content.
        part_id (str): Internal identifier for the attachment within the message parts. Used for download with the Gmail API.
        google_service (GoogleService): Reference to the Google service object used for downloading the attachment.
        id (str | None, optional): ID of the attachment generated by Gmail after a message fetch (.get() method). Defaults to None.
        data (str | None, optional): Base64 encoded content of the attachment data. Defaults to None.
    Methods:
        download(): Downloads the attachment data from the Gmail API (if not already downloaded).
        save(filepath: str | None=None, overwrite: bool=False): Saves the attachment data to a file.
    """  # noqa

    filename: str
    mimeType: str
    part_id: str  # used to map with google attachments
    google_service: GoogleService
    id: str | None = (
        None  # google will generate new id(hash) each time the message is get with .get() method
    )
    data: bytes | None = None
    size: int | None = None  # size in bytes, as reported by Gmail
    content_id: str | None = None  # Content-ID, set for images referenced as cid: in the html
    is_inline: bool = False  # Content-Disposition: inline (usually an image shown in the body)

    def __init__(
        self,
        filename: str,
        mimeType: str,
        part_id: str,
        google_service: GoogleService,
        id: str | None = None,
        data: bytes | None = None,
        size: int | None = None,
        content_id: str | None = None,
        is_inline: bool = False,
    ):
        self.filename = filename
        self.mimeType = mimeType
        self.google_service = google_service
        self.id = id
        self.data = data
        self.part_id = part_id
        self.size = size
        self.content_id = content_id
        self.is_inline = is_inline

    def download(self) -> None:
        """Downloads the attachment data from the Gmail API (if not already downloaded).
        Raises:
                TypeError: If the google_service.message_id attribute is missing.
                HttpError: An exception if there is an error fetching the attachment data from the Gmail API.
        """
        if not self.id:
            return None
        if self.data:
            return None
        if not self.google_service.message_id:
            raise TypeError("Attachment.google_service.message_id missing")
        try:
            res: MessagePartBody | None = (
                self.google_service.service.users()
                .messages()
                .attachments()
                .get(
                    userId=self.google_service.user_id,
                    messageId=self.google_service.message_id,
                    id=self.id,
                )
                .execute()
            )
        except HttpError as e:
            raise e
        finally:
            self.google_service.service.close()
        if not res or "data" not in res:
            return None
        self.data = base64.urlsafe_b64decode(res["data"])

    def save(self, filepath: str | None = None, overwrite: bool = False) -> None:
        """Saves the attachment data to a file.
        Args:
                filepath (str | None, optional): Path to save the attachment. Defaults to the attachment filename.
                overwrite (bool, optional): Whether to overwrite an existing file. Defaults to False.
        Raises:
                FileExistsError: If the target file already exists and overwrite is False.
        """

        if not filepath:
            filepath = self.filename
        if not self.data:
            self.download()
        if os.path.exists(filepath) and not overwrite:
            raise FileExistsError(
                f"""\
                    {filepath} allready exists. \
                    Call save(file_path, overwrite=True) \
                    to rewrite the existing file\
                """
            )
        with open(filepath, "wb") as f:
            f.write(self.data)

    def __str__(self):
        return self.filename


@dataclass
class MessagePart(object):
    """Represents a single part of a Gmail message.
    A message part can be the main body content, an attachment, or a nested structure
    containing further parts.
    Attributes:
            mimeType (str | None): MIME type of the message part content.
            headers (list[MessageHeader]): List of message headers associated with this part.
            parts (list[Self]): List of nested message parts (if any).
            partId (str | None): Internal identifier for the part within the Gmail message.
            filename (str | None): Filename associated with the part (if it's an attachment).
            body (MessagePartBody | None): Information about the part's body content.
    Methods:
            _has_attachments(): Checks if the message part or its nested parts contain attachments.
            get_attachment_by_filename(filename: str) -> Attachment | None: Gets an attachment by its filename.
            get_attachment_by_part_id(id: str) -> Attachment | None: Gets an attachment by its internal part ID.
            attachments: list[Attachment] | None: Property that returns a list of Attachment objects for all attachments within this part and its nested parts.
            get_header(key: str) -> MessageHeader | None: Gets a message header by its name (key).
    """  # noqa

    mimeType: str | None
    headers: list[MessageHeader] = field(default_factory=lambda: [])
    parts: list["MessagePart"] = field(default_factory=lambda: [])
    partId: str | None = None
    filename: str | None = None
    body: MessagePartBody | None = None

    def __init__(self, google_service: GoogleService, **kwargs):
        self.google_service = google_service
        self.mimeType = kwargs.pop("mimeType", None)
        self.filename = kwargs.pop("filename", None)
        self.partId = kwargs.pop("partId", None)
        self.headers = (
            [MessageHeader(**hdr) for hdr in kwargs.pop("headers", None)]
            if "headers" in kwargs
            else []
        )
        self.body = (
            MessagePartBody(**kwargs.pop("body", None)) if "body" in kwargs else None
        )
        self.parts = (
            [
                MessagePart(google_service=self.google_service, **part)
                for part in kwargs.pop("parts", None)
            ]
            if "parts" in kwargs
            else []
        )

    def _has_attachments(self) -> bool:
        """Checks if the message part or its nested parts contain attachments."""
        if self.filename:
            return True
        return any(part._has_attachments() for part in self.parts or [])

    def _as_attachment(self) -> Attachment:
        """This part as an Attachment (only meaningful when the part has a filename)."""
        body = self.body
        content_id = self._header_value("Content-ID")
        disposition = self._header_value("Content-Disposition") or ""
        return Attachment(
            filename=self.filename.replace("/", "_"),
            mimeType=self.mimeType if self.mimeType else "",
            id=body.attachmentId if body else None,
            # small attachments come inline in the message, base64url encoded
            data=base64.urlsafe_b64decode(body.data) if body and body.data else None,
            size=body.size if body else None,
            content_id=content_id.strip("<>") if content_id else None,
            is_inline=disposition.strip().casefold().startswith("inline"),
            google_service=self.google_service,
            part_id=self.partId,
        )

    def _header_value(self, name: str) -> str | None:
        """Value of the first header with this name (case-insensitive)."""
        for header in self.headers or []:
            if header.name.casefold() == name.casefold():
                return header.value
        return None

    def get_attachment_by_filename(self, filename: str) -> Attachment | None:
        """Gets an attachment by its filename."""
        if not filename or len(filename) == 0:
            return None
        if not self._has_attachments():
            return None
        for attachment in self.attachments:
            if attachment.filename == filename:
                return attachment
        return None

    def get_attachment_by_part_id(self, id: str) -> Attachment | None:
        """Gets an attachment by its internal part ID."""
        if not id or len(id) == 0:
            return None
        if not self._has_attachments():
            return None
        for attachment in self.attachments:
            if attachment.part_id == id:
                return attachment
        return None

    @property
    def attachments(self) -> list[Attachment] | None:
        """Property that returns a list of Attachment objects for all attachments within this part and its nested parts"""  # noqa
        attachments = []
        for part in self.parts or []:
            if part.filename:
                attachments.append(part._as_attachment())
            else:
                attachments.extend(part.attachments)
        return attachments

    def get_header(self, key: str) -> MessageHeader | list[MessageHeader] | None:
        """Gets a message header by its name (key)."""
        if not self.headers or len(self.headers) == 0:
            return None
        if not key:
            return self.headers
        for header in self.headers:
            if key == header.name:
                return header
        return None


@dataclass
class Message(object):
    """Represents a single email message within a Gmail account.
    This class provides access to various message properties and functionalities,
    including content retrieval, attachment handling, label management, and
    common actions like marking as read/unread or starring.

    Attributes:
        id (str): Unique identifier for the message.
        snippet (str): Shortened summary of the message content.
        threadId (str): Thread ID that groups related messages together.
        historyId (str): Unique identifier for a specific message history change.
        sizeEstimate (int): Approximate size of the message in bytes.
        internalDate (str): Internal timestamp representing when the message was created.
        payload (MessagePart): Object of type `MessagePart` containing the parsed content
            of the message body and attachments.
        raw (str | None): property containing the raw email data (if available).
        labelIds (list[Labels]): List of label IDs associated with the message.
        labels (list[GmailLabel] | None): List of `GmailLabel` objects representing the
            message's labels (fetched on demand).
    Properties:
        message_headers (list[MessageHeader] | None): List of `MessageHeader` objects
            from the message's payload (if available).
        body (str): Returns the message body content (combines plain text and HTML if both exist).
        html (str): Returns the HTML content of the message body (if available).
        plain (str): Returns the plain text content of the message body (if available).
        alternative (str): Returns the text content of the most appropriate alternative part
            (if message uses multipart/alternative).
        recipient (str): Extracts the recipient's email address from the "To" header (if available).
        message_id (str): Extracts the message ID from the message headers (if available).
        subject (str): Extracts the subject line from the message headers (if available).
        sender (str): Extracts the sender's email address from the "From" header (if available).
        has_attachments (bool): Checks if the message or its nested parts contain attachments.
        attachments (list[Attachment] | None): Returns a list of `Attachment` objects for
            all attachments within the message.
        is_unread (bool): Indicates whether the message has the unread label.
        is_starred (bool): Indicates whether the message has the starred label.
        is_important (bool): Indicates whether the message has the important label.
        is_spam (bool): Indicates whether the message has the spam label.
        is_draft (bool): Indicates whether the message has the draft label.
        is_trash (bool): Indicates whether the message has the trash label.
        created_date (datetime): Converts the `internalDate` to a datetime object representing
            the message creation time.
        date (datetime | None): Parses the "Received" or "Date" header to get the message
            delivery date (if available).
        date_string (str | None): Formats the delivery date according to a specified format string
            (defaults to "%a, %d %b %Y %H:%M:%S %z").
    Methods:
        mark_as_read(self) -> Self: Toggles the unread flag for the message.
        mark_as_unread(self) -> Self: Toggles the unread flag for the message.
        toogle_read_unread(self) -> Self: Shortcut to toggle the unread flag based on the current state.
        mark_spam(self) -> Self: Toggles the spam label for the message.
        mark_not_spam(self) -> Self: Toggles the spam label for the message.
        toggle_spam(self) -> Self: Shortcut to toggle the spam label based on the current state.
        move_to_trash(self) -> Self: Toggles the trash label for the message.
        move_from_trash(self) -> Self: Toggles the trash label for the message.
        toggle_trash(self) -> Self: Shortcut to toggle the trash label based on the current state.
        mark_important(self) -> Self: Toggles the important label for the message.
        mark_not_important(self) -> Self: Toggles the important label for the message.
        toggle_important(self) -> Self: Shortcut to toggle the important label based on the current state.
        mark_starred(self) -> Self: Toggles the starred label for the message.
        mark_not_starred(self) -> Self: Toggles the starred label for the message.
        toggle_starred(self) -> Self: Shortcut to toggle the starred label based on the current state.
        get_attachment(self, filename: str | None = None, id: str | None = None) -> Attachment | None: Retrieves an attachment by filename or internal part ID.
        get_labels(self) -> list[GmailLabel] | None: Fetches and returns a list of `GmailLabel` objects for all labels associated with the message.
        add_label(self, label: [Labels, str]) -> bool: Adds a label to the message.
        add_labels(self, labels: [list[Labels], list[str]]) -> bool: Adds labels to the message.
        remove_label(self, label: [Labels, str]) -> bool: Removes a label from the message.
        remove_labels(self, labels: [list[Labels], list[str]]) -> bool: Removes labels from the message.
        modify_labels(self, labels_to_add: [list[Labels], list[str]] | None, labels_to_remove: [list[Labels], list[str]] | None) -> bool: Updates message labels by adding and/or removing labels.
    """  # noqa

    id: str
    snippet: str
    threadId: str
    historyId: str
    sizeEstimate: int
    internalDate: str
    payload: MessagePart
    raw: str | None = None
    labelIds: list[Labels] = field(default_factory=lambda: [])
    labels: list[GmailLabel] | None = None

    def __init__(self, google_service: GoogleService, **kwargs):
        self.id = kwargs.pop("id", None)
        self.threadId = kwargs.pop("threadId", None)
        self.snippet = kwargs.pop("snippet", None)
        self.historyId = kwargs.pop("historyId", None)
        self.internalDate = kwargs.pop("internalDate", None)
        self.sizeEstimate = kwargs.pop("sizeEstimate", None)
        self.raw = kwargs.pop("raw", None)
        self.labelIds = kwargs.pop("labelIds", None) or []
        # each message keeps its own id, so attachments of listed messages can be downloaded
        self.google_service = _service_for_message(google_service, self.id)
        self.payload = (
            MessagePart(google_service=self.google_service, **kwargs["payload"])
            if kwargs.get("payload")
            else None
        )

    def __str__(self):
        return self.subject if self.subject else (self.snippet if self.snippet else "")

    @property
    def message_headers(self) -> list[MessageHeader] | None:
        if not self.payload:
            return None
        if not self.payload.headers:
            return None
        return self.payload.headers

    def _extract_content(self, part: MessagePart, result: dict) -> None:
        # TODO: load cid: images into content?
        if part.mimeType not in ["text/plain", "text/html"]:
            for sub_part in part.parts:
                self._extract_content(sub_part, result)
        if part.filename:
            # a text file sent as attachment is not part of the body
            return
        if part.mimeType not in result:
            result[part.mimeType] = []
        if not part.body:
            return
        if not part.body.data:
            return
        result[part.mimeType].append(_decode_body(part))

    def _content(self) -> dict | None:
        if not self.payload:
            return None
        result = {}
        if not self.payload.parts:
            if (
                self.payload.mimeType in ["text/plain", "text/html"]
                and self.payload.body
            ):
                if self.payload.body.data:
                    if self.payload.mimeType not in result:
                        result[self.payload.mimeType] = []
                    result[self.payload.mimeType].append(_decode_body(self.payload))
                    return result
            if self.payload.filename or not self.payload.body:
                return None
            if not self.payload.body.data:
                return None
            return {"multipart/alternative": [_decode_body(self.payload)]}
        for part in self.payload.parts:
            self._extract_content(part, result)
        return result

    @property
    def body(self) -> str:
        return self.html if self.html and len(self.html) > 0 else self.plain

    @property
    def html(self) -> str:
        content = self._content()
        if not content:
            return ""
        if "text/html" not in content:
            return ""
        return " ".join(content["text/html"])

    @property
    def plain(self) -> str:
        content = self._content()
        if not content:
            return ""
        if "text/plain" not in content:
            return ""
        return " ".join(content["text/plain"])

    @property
    def alternative(self) -> str:
        content = self._content()
        if not content:
            return ""
        if "multipart/alternative" not in content:
            return ""
        return " ".join(content["multipart/alternative"])

    def header(self, name: str) -> str | None:
        """Value of the first message header with this name (case-insensitive)."""
        if not self.payload:
            return None
        return self.payload._header_value(name)

    @property
    def recipient(self) -> str | None:
        return self.header("To")

    @property
    def cc(self) -> str | None:
        return self.header("Cc")

    @property
    def reply_to(self) -> str | None:
        """The Reply-To header: where the sender wants the answers (may differ from From)."""
        return self.header("Reply-To")

    @property
    def message_id(self) -> str | None:
        return self.header("Message-ID")

    @property
    def in_reply_to(self) -> str | None:
        return self.header("In-Reply-To")

    @property
    def references(self) -> str | None:
        """The References header: Message-IDs of the conversation so far, space separated."""
        return self.header("References")

    @property
    def subject(self) -> str | None:
        return self.header("Subject")

    @property
    def sender(self) -> str | None:
        """Returns only the name or email address of the sender"""
        sender = self.sender_header
        if not sender:
            return None
        if '"' in sender:
            sender = sender.split('"')[1]
        else:
            if "<" in sender:
                sender = sender.split("<")[1].replace(">", "")
        return sender

    @property
    def sender_header(self) -> str | None:
        """Returns the sender message Header"""
        return self.header("From")

    @property
    def has_attachments(self) -> bool:
        if not self.payload:
            return False
        return self.payload._has_attachments()

    @property
    def attachments(self) -> list[Attachment] | None:
        if not self.payload:
            return []
        if self.payload.filename:
            # the whole message is one file (no multipart wrapper)
            return [self.payload._as_attachment()]
        return self.payload.attachments

    def _has_label(self, label: Labels) -> bool:
        return label.value in (self.labelIds or [])

    @property
    def is_unread(self) -> bool:
        return self._has_label(Labels.UNREAD)

    @property
    def is_starred(self) -> bool:
        return self._has_label(Labels.STARRED)

    @property
    def is_important(self) -> bool:
        return self._has_label(Labels.IMPORTANT)

    @property
    def is_spam(self) -> bool:
        return self._has_label(Labels.SPAM)

    @property
    def is_draft(self) -> bool:
        return self._has_label(Labels.DRAFT)

    @property
    def is_trash(self) -> bool:
        return self._has_label(Labels.TRASH)

    @property
    def created_date(self) -> dt:
        """internalDate is the time when messages was created"""
        seconds_from_epoch: int
        try:
            seconds_from_epoch = int(self.internalDate) / 1000
        except ValueError:
            raise ValueError(f"{self.internalDate=} can't be cast to int")
        return dt.fromtimestamp(seconds_from_epoch)

    @property
    def date(self) -> dt | None:
        """returns the date when message was delivered"""
        for name in ("Received", "Date"):
            value = self.header(name)
            if not value:
                continue
            if name == "Received":
                # "from ... by ... ; Tue, 10 Nov 2026 09:15:02 -0800 (PST)"
                value = value.rsplit(";", 1)[-1]
            try:
                return utils.parsedate_to_datetime(value.strip())
            except (TypeError, ValueError):
                continue
        return None

    def date_string(self, format: str | None = DATE_FORMAT) -> str | None:
        """returns fomated delivered date, cheatsheet: https://strftime.org/"""
        if not self.date:
            return None
        date = self.date.astimezone()  # set to locale timezone
        if date.year == dt.now(timezone.utc).astimezone().year:
            format = format.replace(", %Y", "")
        return date.strftime(format)

    @property
    def mark_as_read(self) -> "Message":
        self.remove_label(Labels.UNREAD.value)
        return self

    @property
    def mark_as_unread(self) -> "Message":
        self.add_label(Labels.UNREAD.value)
        return self

    @property
    def toggle_read_unread(self) -> "Message":
        if self.is_unread:
            self.remove_label(Labels.UNREAD.value)
        else:
            self.add_label(Labels.UNREAD.value)
        return self

    @property
    def mark_spam(self) -> "Message":
        self._edit_labels(
            action=LabelAction.TOGGLE,
            add=[Labels.SPAM.value],
            remove=[
                Labels.TRASH.value,
                Labels.INBOX.value,
                Labels.STARRED.value,
                Labels.IMPORTANT.value,
            ],
        )
        return self

    @property
    def mark_not_spam(self) -> "Message":
        self._edit_labels(
            action=LabelAction.TOGGLE,
            add=[Labels.INBOX.value],
            remove=[Labels.SPAM.value],
        )
        return self

    @property
    def toggle_spam(self) -> "Message":
        if self.is_spam:
            self.mark_not_spam
        else:
            self.mark_spam
        return self

    @property
    def move_to_trash(self) -> "Message":
        self._edit_labels(
            action=LabelAction.TOGGLE,
            add=[Labels.TRASH.value],
            remove=[
                Labels.INBOX.value,
                Labels.STARRED.value,
                Labels.IMPORTANT.value,
            ],
        )
        return self

    @property
    def move_from_trash(self) -> "Message":
        self._edit_labels(
            action=LabelAction.TOGGLE,
            add=[Labels.INBOX.value],
            remove=[Labels.TRASH.value],
        )
        return self

    @property
    def toggle_trash(self) -> "Message":
        if self.is_trash:
            self.move_from_trash
        else:
            self.move_to_trash
        return self

    @property
    def mark_important(self) -> "Message":
        self.add_label(Labels.IMPORTANT.value)
        return self

    @property
    def mark_not_important(self) -> "Message":
        self.remove_label(Labels.IMPORTANT.value)
        return self

    @property
    def toggle_important(self) -> "Message":
        if self.is_important:
            return self.mark_not_important
        return self.mark_important

    @property
    def mark_starred(self) -> "Message":
        self.add_label(Labels.STARRED.value)
        return self

    @property
    def mark_not_starred(self) -> "Message":
        self.remove_label(Labels.STARRED)
        return self

    @property
    def toggle_starred(self) -> "Message":
        if self.is_starred:
            return self.mark_not_starred
        return self.mark_starred

    def get_attachment(
        self, filename: str | None = None, id: str | None = None
    ) -> Attachment | None:
        """Retrieves an attachment by filename or internal part ID."""
        if not self.has_attachments:
            return None
        if filename:
            return self.payload.get_attachment_by_filename(filename)
        return self.payload.get_attachment_by_part_id(id)

    @property
    def get_labels(self) -> list[GmailLabel] | None:
        """gets all labels for this message"""
        if not self.labels:
            self.labels = []
        batch = self.google_service.service.new_batch_http_request()

        def get_label_response(request_id, response, exception):
            if exception is not None:
                raise exception
            self.labels.append(GmailLabel(**response))
            return

        for label_id in self.labelIds:
            batch.add(
                self.google_service.service.users()
                .labels()
                .get(userId=self.google_service.user_id, id=label_id),
                callback=get_label_response,
            )
        batch.execute()
        return self.labels

    def add_label(self, label: Labels) -> bool:
        return self._edit_labels(action=LabelAction.ADD, add=[label])

    def add_labels(self, labels: list[Labels]) -> bool:
        return self._edit_labels(action=LabelAction.ADD, add=labels)

    def remove_label(self, label: Labels) -> bool:
        return self._edit_labels(action=LabelAction.REMOVE, remove=[label])

    def remove_labels(self, labels: list[Labels]) -> bool:
        return self._edit_labels(action=LabelAction.REMOVE, remove=labels)

    def modify_labels(
        self,
        labels_to_add: list[Labels] | None,
        labels_to_remove: list[Labels] | None,
    ) -> bool:
        return self._edit_labels(
            action=LabelAction.TOGGLE, add=labels_to_add, remove=labels_to_remove
        )

    def _edit_labels(
        self,
        action: LabelAction,
        add: list[Labels] | None = [],
        remove: list[Labels] | None = [],
    ) -> bool:
        payload = {}
        match action:
            case LabelAction.REMOVE:
                payload["removeLabelIds"] = [x for x in remove]
            case LabelAction.ADD:
                payload["addLabelIds"] = [x for x in add]
            case LabelAction.TOGGLE:
                payload["removeLabelIds"] = [x for x in remove]
                payload["addLabelIds"] = [x for x in add]
            case _:
                return False
        try:
            self.google_service.service.users().messages().modify(
                userId=self.google_service.user_id, id=self.id, body=payload
            ).execute()
            match action:
                case LabelAction.ADD:
                    for label in add:
                        if label not in self.labelIds:
                            self.labelIds.append(label)
                case LabelAction.REMOVE:
                    for label in remove:
                        if label in self.labelIds:
                            self.labelIds.remove(label)
                case LabelAction.TOGGLE:
                    for label in add:
                        if label not in self.labelIds:
                            self.labelIds.append(label)
                    for label in remove:
                        if label in self.labelIds:
                            self.labelIds.remove(label)
                case _:
                    return False
            return True
        except HttpError as e:
            raise e
        finally:
            self.google_service.service.close()


def _service_for_message(google_service: GoogleService, message_id: str | None):
    """The same Gmail connection, bound to this message id (needed to download attachments)."""
    if not isinstance(google_service, GoogleService) or not message_id:
        return google_service
    if google_service.message_id == message_id:
        return google_service
    return GoogleService(
        service=google_service.service,
        user_id=google_service.user_id,
        message_id=message_id,
    )


def _decode_body(part: MessagePart) -> str:
    """Text of a body part, decoded with the charset of its Content-Type (not every email is UTF-8)."""
    raw: bytes = base64.urlsafe_b64decode(part.body.data)
    charset: str = "utf-8"
    content_type = part._header_value("Content-Type")
    if content_type:
        headers = _EmailHeaders()
        headers["Content-Type"] = content_type
        charset = headers.get_content_charset() or charset
    try:
        return raw.decode(charset)
    except (LookupError, UnicodeDecodeError):
        return raw.decode("utf-8", errors="replace")
